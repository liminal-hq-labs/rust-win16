#!/usr/bin/env python3
# Generates src/imports.rs: a far-call stub for every Win16 import in tools/imports.tbl, as `global_asm!` blocks plus `extern "C"` declarations.
#
# (c) Copyright 2026 Liminal HQ, Scott Morris
# SPDX-License-Identifier: Apache-2.0 OR MIT
#
# usage: tools/gen_imports.py [--check-spec DIR] tools/imports.tbl src/imports.rs
#
# Rust calls a stub with the C convention (a 32-bit near call, 4-byte arguments). The stub rebuilds the arguments as the Pascal convention
# wants them (16-bit words, longs as two words, pointers as seg:off), makes the far call and fixes the result up in EAX. The stub's far
# call operand carries a global label `__w16imp_<MODULE>_<ordinal>_<Name>`; the packer reads those labels to write the import fixups.
import os
import re
import sys


def parse_table(path):
	rows = []
	with open(path, encoding="utf-8") as f:
		for line in f:
			line = line.split("#", 1)[0].strip()
			if not line:
				continue
			mod, ordinal, name, args, ret = line.split()
			if args == "-":
				args = ""
			if ret not in ("w", "l", "v") or not re.fullmatch(r"[wlpf]*", args):
				raise SystemExit("bad row: " + line)
			rows.append((mod, int(ordinal), name, args, ret))
	return rows


def stub(mod, ordinal, name, args, ret):
	n = len(args)
	out = []
	out.append(f".section .text.imp_{name},\"ax\"")
	out.append(f".globl {name}")
	out.append(f"{name}:")
	out.append("push ebp")
	out.append("mov bp, sp")
	# Rust keeps values in EBX, ESI and EDI across calls; a 16-bit callee need not keep their high halves, so the stub does.
	out.append("push ebx")
	out.append("push esi")
	out.append("push edi")
	for i, a in enumerate(args):
		off = 8 + 4 * i
		if a == "w":
			out.append(f"push word ptr [bp+{off}]")
		elif a == "l":
			out.append(f"push word ptr [bp+{off + 2}]")
			out.append(f"push word ptr [bp+{off}]")
		elif a == "p":
			out.append("push ds")
			out.append(f"push word ptr [bp+{off}]")
		elif a == "f":
			out.append("push cs")
			out.append(f"push word ptr [bp+{off}]")
	# Rust runs on a 32-bit alias of the stack segment (see `_start` in src/lib.rs); Windows gets the real 16-bit one. `mov ss` holds
	# off interrupts until after the next instruction, so ESP is clean before anything can use it.
	out.append("mov ss, word ptr [__w16_ss16]")
	out.append("movzx esp, sp")
	out.append(".byte 0x9a")
	out.append(f".globl __w16imp_{mod}_{ordinal}_{name}")
	out.append(f"__w16imp_{mod}_{ordinal}_{name}:")
	out.append(".word 0, 0")
	# Windows may have moved the data segment: move the 32-bit alias with it (src/lib.rs). Then back to the 32-bit stack. Windows may leave the high half of ESP as it likes, and an interrupt taken on a 16-bit stack restores
	# only SP, so ESP is rebuilt from SP. Windows does not keep ES, which Rust's string instructions (`rep movs`) take as the data segment.
	out.append(".byte 0x66, 0xe8")
	out.append(".long w16_sync_alias - . - 4")
	out.append("mov ss, word ptr [__w16_ss32]")
	out.append("movzx esp, sp")
	out.append("push ds")
	out.append("pop es")
	if ret == "w":
		out.append("movzx eax, ax")
	elif ret == "l":
		out.append("movzx eax, ax")
		out.append("shl edx, 16")
		out.append("or eax, edx")
	out.append("pop edi")
	out.append("pop esi")
	out.append("pop ebx")
	out.append("pop ebp")
	out.append(".byte 0x66, 0xc3")
	return out


def render(rows):
	o = []
	o.append("// Win16 import stubs and their declarations. Generated by tools/gen_imports.py from tools/imports.tbl; do not edit.")
	o.append("//")
	o.append("// (c) Copyright 2026 Liminal HQ, Scott Morris")
	o.append("// SPDX-License-Identifier: Apache-2.0 OR MIT")
	o.append("#![allow(non_snake_case, dead_code)]")
	o.append("")
	o.append("use core::arch::global_asm;")
	o.append("")
	for mod, ordinal, name, args, ret in rows:
		lines = stub(mod, ordinal, name, args, ret)
		o.append(f"// {mod}.{ordinal} {name}")
		o.append("global_asm!(")
		o.append("\t\".code16\",")
		for ln in lines:
			o.append("\t\"" + ln.replace("\"", "\\\"") + "\",")
		o.append(");")
		o.append("")
	o.append("unsafe extern \"C\" {")
	for mod, ordinal, name, args, ret in rows:
		params = ", ".join(f"a{i}: u32" for i in range(len(args)))
		o.append(f"\tpub fn {name}({params}) -> u32;")
	o.append("}")
	o.append("")
	return "\n".join(o)


def check_spec(rows, spec_dir):
	files = {"KERNEL": "krnl.spec", "USER": "user.exe16.spec", "GDI": "gdi.exe16.spec"}
	bad = 0
	for mod, ordinal, name, args, ret in rows:
		with open(os.path.join(spec_dir, files[mod]), encoding="utf-8") as f:
			text = f.read()
		m = re.search(rf"^{ordinal}\s+\S+(?:\s+-\S+)*\s+(\w+)\(([^)]*)\)", text, re.M)
		if not m:
			print(f"spec mismatch: {mod}.{ordinal} {name} not found")
			bad += 1
			continue
		want = len(m.group(2).split())
		if want != len(args):
			print(f"spec mismatch: {name} has {want} args in the spec ({m.group(1)}), {len(args)} here")
			bad += 1
	return bad


def main():
	argv = sys.argv[1:]
	spec = None
	if argv[:1] == ["--check-spec"]:
		spec = argv[1]
		argv = argv[2:]
	if len(argv) != 2:
		sys.exit(__doc__)
	rows = parse_table(argv[0])
	if spec and check_spec(rows, spec):
		sys.exit(1)
	with open(argv[1], "w", encoding="utf-8", newline="\n") as f:
		f.write(render(rows))


if __name__ == "__main__":
	main()
